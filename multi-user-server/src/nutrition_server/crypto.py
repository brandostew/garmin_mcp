"""Sealing saved logins so they are unreadable at rest.

The secret comes from the ENCRYPTION_SECRET environment variable: any long
random string. On Railway it is generated by Railway itself
(`${{secret(64)}}`), so it never passes through a chat or a file. Whoever
holds it can open the box, which is why the brief asks Brandon to tell
people plainly.
"""

import base64
import hashlib
import json
import os
import secrets

from cryptography.fernet import Fernet

MIN_SECRET_LENGTH = 32


class EncryptionNotConfigured(RuntimeError):
    pass


def encryption_secret() -> str:
    secret = os.environ.get("ENCRYPTION_SECRET", "")
    if len(secret) < MIN_SECRET_LENGTH:
        raise EncryptionNotConfigured(
            f"ENCRYPTION_SECRET must be set to at least {MIN_SECRET_LENGTH} random characters.")
    return secret


def _fernet() -> Fernet:
    digest = hashlib.sha256(b"seal:" + encryption_secret().encode()).digest()
    return Fernet(base64.urlsafe_b64encode(digest))


def new_encryption_secret() -> str:
    """A value for ENCRYPTION_SECRET (for local use; Railway makes its own)."""
    return secrets.token_urlsafe(48)


def seal(data: dict) -> bytes:
    return _fernet().encrypt(json.dumps(data).encode())


def unseal(blob: bytes) -> dict:
    return json.loads(_fernet().decrypt(blob))
